/**
 * Builds the p-x402 test vectors from the TypeScript reference implementation.
 *   bun run vectors          writes spec/test-vectors/*.json
 * vectors.test.ts fails when the committed files differ from what this produces.
 */
import { buildCodecVectors } from "./generator/codec"
import { buildErrorCodeVectors } from "./generator/error-codes"
import { buildMatchingVectors } from "./generator/matching"
import { buildPaywallVectors } from "./generator/paywall"
import { buildTranscriptVectors } from "./generator/transcripts"
import { buildValidationVectors } from "./generator/validation"

export const VECTOR_FORMAT_VERSION = 1

export const VECTOR_FILES = [
  "header-codec.json",
  "validation.json",
  "requirement-matching.json",
  "client-transcripts.json",
  "error-codes.json",
  "paywall-transcripts.json",
] as const

export type VectorFile = (typeof VECTOR_FILES)[number]

/** File name to exact file text. */
export async function buildVectorFiles(): Promise<Record<VectorFile, string>> {
  const bodies: Record<VectorFile, object> = {
    "header-codec.json": buildCodecVectors(),
    "validation.json": await buildValidationVectors(),
    "requirement-matching.json": buildMatchingVectors(),
    "client-transcripts.json": await buildTranscriptVectors(),
    "error-codes.json": buildErrorCodeVectors(),
    "paywall-transcripts.json": await buildPaywallVectors(),
  }
  const out = {} as Record<VectorFile, string>
  for (const name of VECTOR_FILES) {
    const text = JSON.stringify(
      {
        $comment: "Generated by spec/test-vectors/generate.ts (bun run vectors). Do not edit.",
        formatVersion: VECTOR_FORMAT_VERSION,
        ...bodies[name],
      },
      null,
      2,
    )
    out[name] = `${text}\n`
  }
  return out
}

if (import.meta.main) {
  const files = await buildVectorFiles()
  for (const name of VECTOR_FILES) {
    const text = files[name]
    await Bun.write(new URL(name, import.meta.url), text)
    const parsed = JSON.parse(text) as { cases?: unknown[]; codes?: unknown[] }
    console.log(`${name}: ${(parsed.cases ?? parsed.codes ?? []).length}`)
  }
}
